/**
 * Builds src/masterBank.ts: puzzles that need a level-5 technique (Finned
 * Swordfish or Finned Jellyfish). Plain carving almost never stops exactly
 * there (about 1 grid in 200 gets one), which is too slow to do live, so they
 * are found here once and Ranked serves them through a random transform.
 *
 *   npm run build-master-bank -- --count 40
 */
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { countSolutions, createRng, grade, gridToString, randomSolvedGrid, type Grid } from '../src/index.ts';

const { values } = parseArgs({
  options: {
    count: { type: 'string', short: 'n', default: '40' },
    seed: { type: 'string', short: 's', default: 'master-bank-1' },
  },
});
const count = Number(values.count);
const rng = createRng(values.seed!);

/** Carve to the limit of level 4, keeping at least one of every digit among the givens. */
function carveLevel4(solution: Grid): Grid {
  const puzzle = Uint8Array.from(solution);
  const perDigit = new Array(10).fill(9);
  for (const c of rng.shuffle(Array.from({ length: 81 }, (_, i) => i))) {
    if (perDigit[solution[c]] <= 1) continue;
    puzzle[c] = 0;
    if (countSolutions(puzzle) === 1 && grade(puzzle, { maxLevel: 4 }).solved) perDigit[solution[c]]--;
    else puzzle[c] = solution[c];
  }
  return puzzle;
}

/** One more removal that keeps the solution unique, beats level 4 and is solved with level 5. */
function pushToLevel5(puzzle: Grid, solution: Grid): ReturnType<typeof grade> | null {
  const perDigit = new Array(10).fill(0);
  for (const v of puzzle) if (v) perDigit[v]++;
  for (const c of rng.shuffle(Array.from({ length: 81 }, (_, i) => i).filter((i) => puzzle[i]))) {
    if (perDigit[solution[c]] <= 1) continue;
    puzzle[c] = 0;
    if (countSolutions(puzzle) === 1) {
      const result = grade(puzzle, { maxLevel: 5 });
      if (result.solved && result.level === 5) return result;
    }
    puzzle[c] = solution[c];
  }
  return null;
}

const bank: { puzzle: string; rating: number; hardest: string }[] = [];
let grids = 0;
const started = Date.now();
while (bank.length < count) {
  grids++;
  if (grids % 100 === 0) console.log(`  ...${grids} grids, ${bank.length} found, ${Math.round((Date.now() - started) / 1000)}s`);
  const solution = randomSolvedGrid(rng);
  const puzzle = carveLevel4(solution);
  const result = pushToLevel5(puzzle, solution);
  if (!result) continue;
  bank.push({ puzzle: gridToString(puzzle), rating: result.rating, hardest: result.hardest! });
  console.log(`${bank.length}/${count}: ${result.hardest}, rating ${result.rating} (${grids} grids, ${Math.round((Date.now() - started) / 1000)}s)`);
}

bank.sort((a, b) => a.rating - b.rating);
const lines = bank.map((p) => `  { puzzle: '${p.puzzle}', rating: ${p.rating}, hardest: '${p.hardest}' },`);
writeFileSync(
  new URL('../src/masterBank.ts', import.meta.url),
  `import type { TechniqueId } from './techniques.ts';

/**
 * Level-5 puzzles (Finned Swordfish / Finned Jellyfish), sorted by rating.
 * Generated by scripts/build-master-bank.ts (seed ${values.seed}); don't edit by
 * hand. Ranked never serves one as-is: generator.ts disguises each with a
 * random transform.
 */
export const MASTER_BANK: readonly { puzzle: string; rating: number; hardest: TechniqueId }[] = [
${lines.join('\n')}
];
`,
);
console.log(`Wrote ${bank.length} puzzles from ${grids} grids.`);
